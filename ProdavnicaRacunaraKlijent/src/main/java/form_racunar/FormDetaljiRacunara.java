    private void popuniTipoveRacunara() {
        try {
            ArrayList<TipRacunara> tipoviRacunara = ClientController.getInstance().getAllTipRacunara();

            cmbTipRacunara.removeAllItems();

            for (TipRacunara tipRacunara : tipoviRacunara) {
                cmbTipRacunara.addItem(tipRacunara);
            }

        } catch (Exception ex) {
            //  Logger.getLogger(FormNoviRacunar.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

