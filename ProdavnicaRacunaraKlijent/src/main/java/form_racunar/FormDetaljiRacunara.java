    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed

        try {

            if (txtCenaPoKom.getText().isEmpty() || txtNaziv.getText().isEmpty()
                    || txtOpis.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }

            String naziv = txtNaziv.getText();
            String opis = txtOpis.getText();
            TipRacunara tipRacunara = (TipRacunara) cmbTipRacunara.getSelectedItem();
            double cenaPoKomadu = ((Number) txtCenaPoKom.getValue()).doubleValue();

            r.setNaziv(naziv);
            r.setOpis(opis);
            r.setTipRacunara(tipRacunara);
            r.setCenaPoKomadu(cenaPoKomadu);

            ClientController.getInstance().updateRacunar(r);
            FormPretragaRacunara fp = (FormPretragaRacunara) getParent();
            fp.refreshTable();
            fp.popuniRacunare();
            JOptionPane.showMessageDialog(this, "Uspesno izmenjen racunar.");
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
//            Logger.getLogger(FormDetaljiRacunara.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnIzmeniActionPerformed

