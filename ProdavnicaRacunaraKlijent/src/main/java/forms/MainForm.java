    private void miOdjavaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_miOdjavaActionPerformed
        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da "
                + "se odjavite?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().logout(ulogovani);
                new LoginForm().setVisible(true);
                Session.getInstance().setUlogovani(null);
                this.dispose();
            } catch (Exception ex) {
                Logger.getLogger(MainForm.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_miOdjavaActionPerformed

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed

        int row = tblStavke.getSelectedRow();

        if (row >= 0) {
            TableModelStavke tm = (TableModelStavke) tblStavke.getModel();
            tm.obrisiStavku(row);

            cena = tm.vratiCenuRacuna();
            lblCena.setText(String.valueOf(cena) + "din");
        }

    }//GEN-LAST:event_btnObrisiActionPerformed

    private void txtKolicinaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtKolicinaKeyReleased

        if (evt.getKeyChar() >= '0' && evt.getKeyChar() <= '9') {

            Racunar r = (Racunar) cmbRacunar.getSelectedItem();
            int kolicina = Integer.parseInt(txtKolicina.getText());

            if (kolicina == 0) {
                txtKolicina.setText("");
                txtCenaStavke.setText("");
                return;
            }

            txtCenaStavke.setText(String.valueOf(r.getCenaPoKomadu() * kolicina));

        } else {
            txtKolicina.setText("");
            txtCenaStavke.setText("");
        }

    }//GEN-LAST:event_txtKolicinaKeyReleased

    private void cmbRacunarItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cmbRacunarItemStateChanged

        if (cmbRacunar.getSelectedItem() != null) {

            if (txtKolicina.getText().isEmpty()) {
                txtCenaStavke.setText("");
                return;
            }

            Racunar r = (Racunar) cmbRacunar.getSelectedItem();
            int kolicina = Integer.parseInt(txtKolicina.getText());

            if (kolicina == 0) {
                txtKolicina.setText("");
                txtCenaStavke.setText("");
                return;
            }

            txtCenaStavke.setText(String.valueOf(r.getCenaPoKomadu() * kolicina));
        }

    }//GEN-LAST:event_cmbRacunarItemStateChanged

    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed

        if (txtKolicina.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kolicina mora biti popunjena!");
            return;
        }

        Racunar r = (Racunar) cmbRacunar.getSelectedItem();
        int kolicina = Integer.parseInt(txtKolicina.getText());
        double cenaStavke = Double.parseDouble(txtCenaStavke.getText());

        TableModelStavke tm = (TableModelStavke) tblStavke.getModel();

        StavkaRacuna sr = new StavkaRacuna();
        sr.setKolicina(kolicina);
        sr.setCena(cenaStavke);
        sr.setRacunar(r);

        tm.dodajStavku(sr);

        cena = tm.vratiCenuRacuna();
        lblCena.setText(String.valueOf(cena) + "din");


    }//GEN-LAST:event_btnDodajActionPerformed

    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed

        try {
            TableModelStavke tm = (TableModelStavke) tblStavke.getModel();

            if (tm.getLista().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Racun mora imati bar jednu stavku!");
                return;
            }

            Racun r = new Racun();
            r.setDatumVreme(new Date());
            r.setCena(cena);
            r.setAdministrator(ulogovani);
            r.setStavkeRacuna(tm.getLista());

            ClientController.getInstance().addRacun(r);
            resetujFormu();
            JOptionPane.showMessageDialog(this, "Uspesno sacuvan racun!");

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }

    }//GEN-LAST:event_btnSacuvajActionPerformed

