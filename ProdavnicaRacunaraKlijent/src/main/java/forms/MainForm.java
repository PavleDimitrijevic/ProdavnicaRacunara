    public void popuniRacunare() {
        try {
            ArrayList<Racunar> racunari = ClientController.getInstance().getAllRacunar(null);

            cmbRacunar.removeAllItems();

            for (Racunar racunar : racunari) {
                cmbRacunar.addItem(racunar);
            }

        } catch (Exception ex) {
            //Logger.getLogger(FormNoviRacunar.class.getName()).log(Level.SEVERE, null, ex);
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }

    private void resetujFormu() {
        txtKolicina.setText("");
        txtCenaStavke.setText("");
        lblCena.setText("0.00din");
        cena = 0;
        TableModelStavke tm = (TableModelStavke) tblStavke.getModel();
        tm.getLista().clear();
        tm.fireTableDataChanged();
    }

